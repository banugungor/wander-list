/** English name in, localized name out. Falls back to the original English
 * name when no Turkish entry exists (e.g. an unmapped micro-territory) or
 * when `language` is "en". */
export function getLocalizedCountryName(name: string, language: Language): string {
  if (language === "en") return name;
  return COUNTRY_NAME_TR[name] ?? name;
}

/** heritageSites.json's `country` field: usually a single name, but ~51
 * transnational sites list several comma-joined names. */
export function getLocalizedCountryField(countryField: string, language: Language): string {
  if (language === "en") return countryField;
  return countryField
    .split(",")
    .map((token) => getLocalizedCountryName(token.trim(), language))
    .join(", ");
}
