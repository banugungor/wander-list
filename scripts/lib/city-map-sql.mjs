// Turns one built city map (the object scripts/build-city-map.mjs assembles)
// into an idempotent upsert for the Supabase `city_maps` table
// (scripts/city_maps_schema.sql). Re-running it replaces the row and bumps
// `updated_at`, which makes every device re-download that city's map.
const literal = (value) => `'${String(value).replaceAll("'", "''")}'`;

export function cityMapSql(map) {
  const columns = [
    ["id", literal(map.id)],
    ["name", literal(map.name)],
    ["name_tr", literal(map.nameTr)],
    ["bbox", `${literal(JSON.stringify(map.bbox))}::jsonb`],
    ["width", map.width],
    ["height", map.height],
    ["labels", `${literal(JSON.stringify(map.labels))}::jsonb`],
    ["water", literal(map.water)],
    ["green", literal(map.green)],
    ["rivers", literal(map.rivers)],
    ["canals", literal(map.canals)],
    ["minor", literal(map.minor)],
    ["major", literal(map.major)],
  ];
  const names = columns.map(([name]) => name);
  const updates = names.filter((name) => name !== "id").map((name) => `${name} = excluded.${name}`);
  return `-- Generated by scripts/build-city-map.mjs — ${map.name}. Run after city_maps_schema.sql.
insert into public.city_maps (${names.join(", ")}, updated_at)
values (${columns.map(([, value]) => value).join(", ")}, now())
on conflict (id) do update set ${updates.join(", ")}, updated_at = now();
`;
}
